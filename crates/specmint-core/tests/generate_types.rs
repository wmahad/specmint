/// High-value Kubb-parity contracts: const literals, strip_readonly on requests,
/// freeform `{}` → `any`, array-of-union parens, and cycle-aware factories.
#[test]
fn parity_fixture_covers_kubb_critical_behaviors() {
    let dir = tempdir().unwrap();
    let out = dir.path().join("generated");
    let cache = dir.path().join("cache");
    let fixture =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/parity.openapi.yaml");

    let config_path = dir.path().join("specmint.toml");
    let toml = format!(
        r#"
[source]
path = "{fixture}"

[source.cache]
dir = "{cache}"

[output]
path = "{out}"
clean = true

[adapter]
validate = true

[emitters.types]
enabled = true
file = "types.ts"
enum_style = "enum"
strip_readonly = true
compact = true

[emitters.factories]
enabled = true
file = "factories.ts"
seed = 2

[emitters.msw]
enabled = false
"#,
        fixture = fixture.display(),
        cache = cache.display(),
        out = out.display(),
    )
    .replace('\\', "/");
    std::fs::write(&config_path, toml).unwrap();

    generate(GenerateOptions {
        config: ConfigSource::Path(config_path),
        mode: None,
        emitter_filter: None,
        force: true,
        write_schema: None,
    })
    .unwrap();

    let types = std::fs::read_to_string(out.join("types.ts")).unwrap();

    // const → required string literal (discriminator narrowing)
    assert!(
        types.contains("type: 'evidence'"),
        "const discriminator should emit a required literal:\n{types}"
    );
    assert!(types.contains("type: 'data'"));

    // freeform `{}` → any
    assert!(
        types.contains("export type TableConfig = any"),
        "bare object schema should be any:\n{types}"
    );
    assert!(types.contains("table_config?: any | null") || types.contains("table_config?: any"));

    // Discriminated oneOf (Kubb preserve): (Arm & { type: 'value' }) | …
    assert!(
        types.contains("(EvidenceRequirement & { type: 'evidence' })")
            && types.contains("(DataRequirement & { type: 'data' })"),
        "discriminator mapping must narrow arms:\n{types}"
    );
    assert!(
        types.contains(
            "((EvidenceRequirement & { type: 'evidence' }) | (DataRequirement & { type: 'data' }))[]"
        ) || types.contains(
            "((DataRequirement & { type: 'data' }) | (EvidenceRequirement & { type: 'evidence' }))[]"
        ),
        "array of discriminated union must parenthesize:\n{types}"
    );

    // Component parameter / response / requestBody $refs resolve
    assert!(
        types.contains("export type GetNodePathParams") && types.contains("nodeId: string"),
        "path-item parameter $ref must resolve:\n{types}"
    );
    assert!(
        types.contains("export type GetNode200"),
        "response $ref must resolve to schema type:\n{types}"
    );

    // Item-root nullable on array items is stripped (Kubb: string[], not (string | null)[])
    assert!(
        types.contains("type_ids?: string[]"),
        "array item nullable should not become (string | null)[]:\n{types}"
    );
    assert!(
        !types.contains("(string | null)[]"),
        "must not emit array-of-nullables:\n{types}"
    );

    // OAS 3.1 `anyOf: [T, {type: null}]` → `T | null` (not `| any`)
    assert!(
        types.contains("enforced?: boolean | null"),
        "type: null arm must become | null:\n{types}"
    );
    assert!(
        types.contains("status?: string | null"),
        "ref/primitive + null anyOf must become | null:\n{types}"
    );
    assert!(
        !types.contains("boolean | any") && !types.contains("string | any"),
        "type: null must not become any:\n{types}"
    );

    // Response Entity keeps readOnly id
    assert!(
        types.contains("export type Entity = {") && types.contains("id: string"),
        "Entity response should keep id:\n{types}"
    );

    // Request body strips readOnly id
    assert!(
        types.contains("export type CreateEntityMutationRequest"),
        "missing CreateEntityMutationRequest:\n{types}"
    );
    let request_idx = types
        .find("export type CreateEntityMutationRequest")
        .expect("request type");
    let request_slice = &types[request_idx..];
    let request_end = request_slice
        .find("\nexport ")
        .unwrap_or(request_slice.len().min(400));
    let request_slice = &request_slice[..request_end];
    assert!(
        !request_slice.contains("id:"),
        "strip_readonly should omit id from request:\n{request_slice}"
    );
    assert!(
        request_slice.contains("name:"),
        "request should still include name:\n{request_slice}"
    );
    assert!(
        request_slice.contains("languages?: LanguageEnum[]"),
        "strip_readonly must keep enum $ref aliases (not inline 'en' | 'nl'[]):\n{request_slice}"
    );

    // Header params (additive Kubb surface)
    assert!(
        types.contains("export type GetNodeHeaderParams")
            && types.contains("'X-Client-Token'?: string"),
        "header parameters should emit HeaderParams:\n{types}"
    );

    // NullEnum / enum-with-null / type:[T,null] / allOf flatten+merge
    assert!(
        types.contains("export type NullEnum = null"),
        "NullEnum should be null, not never:\n{types}"
    );
    assert!(
        types.contains("Open = 'open'")
            && types.contains("Closed = 'closed'")
            && !types.contains("Null = null"),
        "enum-with-null should strip null members:\n{types}"
    );
    assert!(
        types.contains("export type MultiTypeFlag = boolean | null"),
        "type:[boolean,null] should become boolean | null:\n{types}"
    );
    assert!(
        types.contains("export type WrappedName = string"),
        "single-member allOf should flatten:\n{types}"
    );
    assert!(
        types.contains("export type MergedProfile = {")
            && types.contains("first: string")
            && types.contains("last?: string"),
        "adjacent allOf objects should merge:\n{types}"
    );

    // writeOnly: named schemas keep write fields; inlined responses strip them
    assert!(
        types.contains("export type SecretBundle = {") && types.contains("password?: string"),
        "named schemas must keep writeOnly fields:\n{types}"
    );
    let inline_idx = types
        .find("export type GetSecretInline200")
        .expect("inlined response type");
    let inline_slice = &types[inline_idx..];
    let inline_end = inline_slice
        .find("\nexport ")
        .unwrap_or(inline_slice.len().min(400));
    let inline_slice = &inline_slice[..inline_end];
    assert!(
        inline_slice.contains("public_id: string") && !inline_slice.contains("password"),
        "inlined response must omit writeOnly:\n{inline_slice}"
    );

    let factories = std::fs::read_to_string(out.join("factories.ts")).unwrap();
    assert!(factories.contains("export function createNode("));
    assert!(factories.contains("export function createNodeChild("));
    // Self/mutual cycles must not infinitely nest createNode() inside createNode().
    // Cycle break uses undefined or a lazy getter shape.
    assert!(
        factories.contains("undefined")
            || factories.contains("get ")
            || factories.contains("Object.defineProperty"),
        "cycle graphs should break materialization:\n{factories}"
    );
    // allOf merge prefers Object.assign when multiple object arms
    assert!(
        factories.contains("Object.assign") || factories.contains("first:"),
        "allOf factories should merge arms:\n{factories}"
    );
}

