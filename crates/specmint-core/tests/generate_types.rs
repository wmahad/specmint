#[test]
fn generates_factories_msw_and_zod() {
    let dir = tempdir().unwrap();
    let out = dir.path().join("generated");
    let cache = dir.path().join("cache");
    let fixture =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/tiny.openapi.yaml");

    let config_path = dir.path().join("specmint.toml");
    let toml = format!(
        r#"
[source]
path = "{fixture}"

[source.cache]
dir = "{cache}"

[output]
path = "{out}"
clean = true

[plugins.types]
enabled = true
file = "types.ts"
enum_style = "enum"
compact = true

[plugins.factories]
enabled = true
file = "factories.ts"
seed = 2

[plugins.msw]
enabled = true
file = "handlers.ts"
parser = "faker"
base_url = "*"

[plugins.zod]
enabled = true
file = "zod.ts"
inferred = true
"#,
        fixture = fixture.display(),
        cache = cache.display(),
        out = out.display(),
    )
    .replace('\\', "/");
    std::fs::write(&config_path, toml).unwrap();

    generate(GenerateOptions {
        config: ConfigSource::Path(config_path),
        mode: None,
        plugins: specmint::plugins::builtin(),
        plugin_filter: None,
        force: true,
        write_schema: None,
    })
    .unwrap();

    let types = std::fs::read_to_string(out.join("types.ts")).unwrap();
    assert!(types.contains("export type ListPetsQueryResponse = ListPets200"));
    assert!(types.contains("export type CreatePetMutationResponse = CreatePet201"));
    assert!(types.contains("export type ListPets400"));

    let factories = std::fs::read_to_string(out.join("factories.ts")).unwrap();
    assert!(factories.contains("export function createPet("));
    assert!(factories.contains("export function createAccountTypeEnum("));
    assert!(factories.contains("DeepPartial"));
    assert!(factories.contains("configureFaker"));
    let seed_lines: Vec<&str> = factories
        .lines()
        .filter(|l| l.contains("faker.seed(2)"))
        .collect();
    assert_eq!(
        seed_lines,
        vec!["faker.seed(2);"],
        "expected exactly one unindented, module-level faker.seed(2):\n{factories}"
    );
    let seed_offset = factories.find("faker.seed(2);").unwrap();
    let first_factory_offset = factories.find("export function create").unwrap();
    assert!(
        seed_offset < first_factory_offset,
        "faker.seed must run before any factory is defined:\n{factories}"
    );
    assert!(factories.contains("arrayOf(() =>"));
    assert!(factories.contains("min: 1, max: 3"));
    // Kubb v5 ignores nullable for mock values — no maybeNull helper.
    assert!(!factories.contains("function maybeNull"));
    assert!(!factories.contains("maybeNull("));
    assert!(!factories.contains("depthStub<"));
    assert!(!factories.contains("__ctx"));
    assert!(!factories.contains("maxDepth"));
    // Explicit undefined must clear defaults (not be skipped like Object.assign).
    assert!(!factories.contains("if (value === undefined) continue;"));
    // Nested refs reuse factories (no depth ctx).
    assert!(factories.contains("createPet()"));
    assert!(factories.contains("createAccountTypeEnum()"));
    // Prefer typed defaults over trailing `} as TypeName`.
    assert!(!factories.contains("} as Pet;"));
    assert!(!factories.contains("} as Announcement;"));
    assert!(factories.contains("const defaults: Pet ="));

    let handlers = std::fs::read_to_string(out.join("handlers.ts")).unwrap();
    assert!(handlers.contains("export function listPetsHandler("));
    assert!(handlers.contains("listPetsHandler.response ="));
    assert!(handlers.contains("listPetsHandler.success ="));
    assert!(handlers.contains("export const listPetsHandlerResponse200"));
    assert!(handlers.contains("switch (status)"));
    assert!(handlers.contains("isResolver("));
    // No footprint-doubling registry by default — consumers import the handlers they need.
    assert!(!handlers.contains("export const handlers ="));
    assert!(!handlers.contains("generatedHandlers"));
    assert!(!handlers.contains("ResponseBuilders"));
    assert!(!handlers.contains("body as never"));
    assert!(handlers.contains("HttpResponse.json"));
    assert!(handlers.contains("createPetHandler("));
    // OpenAPI `{petId}` must become MSW `:petId` or parameterized routes never match.
    assert!(handlers.contains("http.get('*/pets/:petId'"));
    assert!(!handlers.contains("{petId}"));
    // Option bags only — do not treat API bodies with a `status` field as options.
    assert!(handlers.contains("keys.every((key) => key === 'status'"));

    let zod = std::fs::read_to_string(out.join("zod.ts")).unwrap();
    assert!(zod.contains("export const petSchema"));
    assert!(zod.contains("export const accountTypeEnumSchema"));
    assert!(zod.contains("PetFromZod"));
}

