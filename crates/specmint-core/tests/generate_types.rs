#[test]
fn enum_member_naming_matches_clean_script() {
    use specmint::config::EnumMemberNamingRule;
    use specmint::naming::enum_member_name_with_rule;
    let rule = EnumMemberNamingRule::default();
    assert_eq!(
        enum_member_name_with_rule("Status", "no_additives", &rule),
        "NoAdditives"
    );
    assert_eq!(
        enum_member_name_with_rule("Status", "HTTP_OK", &rule),
        "HTTP_OK"
    );
    assert_eq!(enum_member_name_with_rule("Status", "OK", &rule), "OK");
    assert_eq!(
        enum_member_name_with_rule("HTTPHeader", "5_5_ETAG", &rule),
        "HTTPHeader55ETAG"
    );
}

#[test]
fn naming_config_applies_schema_prefix_and_rename_override() {
    use specmint::config::NamingConfig;
    use specmint::naming::Naming;

    let raw = r#"
[schema]
prefix = "I"
suffix = "Dto"
preserve_valid_identifier = false

[[overrides]]
match = { kind = "schema_name", pattern = "^Legacy" }
rename = "ModernName"
"#;
    let cfg = toml::from_str::<NamingConfig>(raw).unwrap().normalize();
    let naming = Naming::new(cfg).unwrap();
    assert_eq!(naming.schema_type_name("pet_status"), "IPetStatusDto");
    assert_eq!(naming.schema_type_name("LegacyFoo"), "ModernName");
    assert_eq!(naming.factory_name("Pet"), "createPet");
    assert_eq!(naming.handler_name("list_pets"), "listPetsHandler");
    assert_eq!(naming.zod_name("PetStatus"), "petStatusSchema");
}

#[test]
fn generates_types_file_from_fixture() {
    let dir = tempdir().unwrap();
    let out = dir.path().join("generated");
    let cache = dir.path().join("cache");
    let fixture =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/tiny.openapi.yaml");

    let config_path = dir.path().join("specmint.toml");
    let toml = format!(
        r#"
[source]
path = "{fixture}"

[source.cache]
dir = "{cache}"

[output]
path = "{out}"
clean = true

[naming]
schema_case = "PascalCase"

[[naming.overrides]]
match = {{ kind = "schema_name", pattern = "Discriminator$" }}
enum_style = "literal"

[emitters.types]
enabled = true
file = "types.ts"
enum_style = "enum"
strip_readonly = true
compact = true

[emitters.factories]
enabled = false

[emitters.msw]
enabled = false
"#,
        fixture = fixture.display(),
        cache = cache.display(),
        out = out.display(),
    );
    // Windows-safe: TOML strings need forward slashes or escaped backslashes
    let toml = toml.replace('\\', "/");
    std::fs::write(&config_path, toml).unwrap();

    let report = generate(GenerateOptions {
        config: ConfigSource::Path(config_path),
        mode: Some(GenerateMode::Types),
        emitter_filter: None,
        force: true,
        write_schema: None,
    })
    .unwrap();

    assert!(!report.skipped);
    let types_path = out.join("types.ts");
    let contents = std::fs::read_to_string(types_path).unwrap();

    assert!(contents.contains("export enum AccountTypeEnum"));
    assert!(contents.contains("Free = 'free'"));
    assert!(contents.contains("NoAdditives = 'no_additives'"));
    assert!(contents.contains("export type CardTypeDocumentDiscriminator = 'document'"));
    assert!(contents.contains("export type Pet = {"));
    assert!(contents.contains("export type ListPetsQueryParams"));
    assert!(contents.contains("Generated by specmint"));
}

#[test]
fn generates_factories_msw_and_zod() {
    let dir = tempdir().unwrap();
    let out = dir.path().join("generated");
    let cache = dir.path().join("cache");
    let fixture =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/tiny.openapi.yaml");

    let config_path = dir.path().join("specmint.toml");
    let toml = format!(
        r#"
[source]
path = "{fixture}"

[source.cache]
dir = "{cache}"

[output]
path = "{out}"
clean = true

[emitters.types]
enabled = true
file = "types.ts"
enum_style = "enum"
compact = true

[emitters.factories]
enabled = true
file = "factories.ts"
seed = 2

[emitters.msw]
enabled = true
file = "handlers.ts"
parser = "faker"
base_url = "*"

[emitters.zod]
enabled = true
file = "zod.ts"
inferred = true
"#,
        fixture = fixture.display(),
        cache = cache.display(),
        out = out.display(),
    )
    .replace('\\', "/");
    std::fs::write(&config_path, toml).unwrap();

    generate(GenerateOptions {
        config: ConfigSource::Path(config_path),
        mode: None,
        emitter_filter: None,
        force: true,
        write_schema: None,
    })
    .unwrap();

    let types = std::fs::read_to_string(out.join("types.ts")).unwrap();
    assert!(types.contains("export type ListPetsQueryResponse = ListPets200"));
    assert!(types.contains("export type CreatePetMutationResponse = CreatePet201"));
    assert!(types.contains("export type ListPets400"));

    let factories = std::fs::read_to_string(out.join("factories.ts")).unwrap();
    assert!(factories.contains("export function createPet("));
    assert!(factories.contains("export function createAccountTypeEnum("));
    assert!(factories.contains("DeepPartial"));
    assert!(factories.contains("configureFaker"));
    // Kubb v5: reseed at the start of every createX (identical first picks across factories).
    assert!(factories.contains("faker.seed(2);"));
    assert!(
        factories
            .lines()
            .filter(|l| l.trim() == "faker.seed(2);")
            .count()
            > 1,
        "expected per-factory faker.seed(2), not only configureFaker"
    );
    assert!(factories.contains("arrayOf(() =>"));
    assert!(factories.contains("min: 1, max: 3"));
    // Kubb v5 ignores nullable for mock values — no maybeNull helper.
    assert!(!factories.contains("function maybeNull"));
    assert!(!factories.contains("maybeNull("));
    assert!(!factories.contains("depthStub<"));
    assert!(!factories.contains("__ctx"));
    assert!(!factories.contains("maxDepth"));
    // Explicit undefined must clear defaults (not be skipped like Object.assign).
    assert!(!factories.contains("if (value === undefined) continue;"));
    // Nested refs reuse factories (no depth ctx).
    assert!(factories.contains("createPet()"));
    assert!(factories.contains("createAccountTypeEnum()"));
    // Prefer typed defaults over trailing `} as TypeName`.
    assert!(!factories.contains("} as Pet;"));
    assert!(!factories.contains("} as Announcement;"));
    assert!(factories.contains("const defaults: Pet ="));

    let handlers = std::fs::read_to_string(out.join("handlers.ts")).unwrap();
    assert!(handlers.contains("export function listPetsHandler("));
    assert!(handlers.contains("listPetsHandler.response ="));
    assert!(handlers.contains("listPetsHandler.success ="));
    assert!(handlers.contains("export const listPetsHandlerResponse200"));
    assert!(handlers.contains("switch (status)"));
    assert!(handlers.contains("isResolver("));
    // No footprint-doubling registry by default — consumers import the handlers they need.
    assert!(!handlers.contains("export const handlers ="));
    assert!(!handlers.contains("generatedHandlers"));
    assert!(!handlers.contains("ResponseBuilders"));
    assert!(!handlers.contains("body as never"));
    assert!(handlers.contains("HttpResponse.json"));
    assert!(handlers.contains("createPetHandler("));
    // OpenAPI `{petId}` must become MSW `:petId` or parameterized routes never match.
    assert!(handlers.contains("http.get('*/pets/:petId'"));
    assert!(!handlers.contains("{petId}"));
    // Option bags only — do not treat API bodies with a `status` field as options.
    assert!(handlers.contains("keys.every((key) => key === 'status'"));

    let zod = std::fs::read_to_string(out.join("zod.ts")).unwrap();
    assert!(zod.contains("export const petSchema"));
    assert!(zod.contains("export const accountTypeEnumSchema"));
    assert!(zod.contains("PetFromZod"));
}

